	/** What item [id] restores of [stat] when its most is [max]; 0 for nothing. */
	@JvmStatic
	fun restore(id: Int, stat: Int, max: Int): Int {
		val e: IntArray = TABLE[id] ?: return 0
		var i: Int = 0
		while (i < e.size) {
			if (e[i] == stat) {
				return e[i + 1] + max * e[i + 2] / 100
			}
			i += 3
		}
		return 0
	}

