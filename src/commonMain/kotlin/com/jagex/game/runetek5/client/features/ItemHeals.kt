 * preview (RuneLite's ItemStatChanges, for the bars' five stats). Made from the Void server: food is its
 * items' `heals` (lifepoints; a range counts its most, RuneLite's theoretical change), potions are its
 * PotionEffects (a flat amount plus a percent of the stat's most: prayer potion 7 + 25%, super prayer 7 + 35%,
 * super restore 8 + 25%, Saradomin brew 20 + 15% lifepoints, energy 10 and super energy 20 run energy,
 * Guthix rest 50 lifepoints and 5 run energy, recover special 25, summoning potion 7 + 25%).
 */
